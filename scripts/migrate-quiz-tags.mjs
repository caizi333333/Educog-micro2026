// 全部 50 个二级知识点（用于覆盖报告）
const L2 = [];
for (const [ch, n] of Object.entries({1:5,2:6,3:6,4:6,5:6,6:4,7:4,8:5,9:4,10:4}))
  for (let i=1;i<=n;i++) L2.push(`${ch}.${i}`);

const src = readFileSync(PATH, 'utf8');
const lines = src.split('\n');
const idRe = /^\s*id:\s*(\d+),/;
let curId = null, kaChanges = 0, chChanges = 0;

for (let i=0;i<lines.length;i++){
  const m = lines[i].match(idRe);
  if (m){ curId = parseInt(m[1]); continue; }
  if (curId!=null && MAP[curId]){
    const newKa = MAP[curId];
    const newCh = newKa.split('.')[0];
    if (/^\s*ka:\s*'/.test(lines[i])){
      const before = lines[i];
      lines[i] = lines[i].replace(/ka:\s*'[^']*'/, `ka: '${newKa}'`);
      if (lines[i]!==before) kaChanges++;
    }
    if (/^\s*chapter:\s*\d+/.test(lines[i])){
      const before = lines[i];
      lines[i] = lines[i].replace(/chapter:\s*\d+/, `chapter: ${newCh}`);
      if (lines[i]!==before) chChanges++;
      curId = null; // chapter 是每题最后一个字段
    }
  }
}

// 覆盖报告（基于 MAP 的最终 ka）
const cnt = {};
for (const ka of Object.values(MAP)) cnt[ka] = (cnt[ka]||0)+1;
const lt3 = L2.filter(k => (cnt[k]||0) < 3);
const report = L2.map(k => `${(cnt[k]||0).toString().padStart(2)}  ${k}`).join('\n');

console.log(`题库总题数: ${Object.keys(MAP).length}`);
console.log(`ka 改写: ${kaChanges} 处, chapter 改写: ${chChanges} 处`);
console.log(`\n== 二级知识点覆盖(题数  id) ==\n${report}`);
console.log(`\n== 仍 <3 题、需补的二级点 (${lt3.length}个) ==\n${lt3.map(k=>`${k}(${cnt[k]||0})`).join('  ')}`);
const need = lt3.reduce((s,k)=>s+(3-(cnt[k]||0)),0);
